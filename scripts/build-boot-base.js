#!/usr/bin/env node
/* Concatenate the small boot modules into one cacheable request.
   `app.js` stays separate so the shell stays readable and lazy modules are
   still loaded on demand. Usage: node scripts/build-boot-base.js [--check] */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'js', 'v10', 'boot-base.js');
const FILES = [
  'js/units/manifest.js',
  'js/v10/icons.js',
  'js/v10/progress.js',
  'js/v10/fx.js',
  'js/v10/units.js',
  'js/v10/render.js',
  'js/v10/router.js'
];

function build() {
  const header = '/* generated by scripts/build-boot-base.js - do not edit. Sources: ' + FILES.join(', ') + ' */\n';
  return header + FILES.map((file) => {
    const text = fs.readFileSync(path.join(ROOT, file), 'utf8');
    return '\n/* ---- ' + file + ' ---- */\n' + text.replace(/\s*$/, '\n');
  }).join('');
}

const output = build();
if (process.argv.includes('--check')) {
  let current = '';
  try { current = fs.readFileSync(OUT, 'utf8'); } catch (e) { /* missing */ }
  if (current !== output) {
    console.error('boot-base.js is stale; run node scripts/build-boot-base.js');
    process.exit(1);
  }
  console.log('boot-base.js is current');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, output);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + Buffer.byteLength(output) + ' bytes)');
}
