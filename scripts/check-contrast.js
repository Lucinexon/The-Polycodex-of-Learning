#!/usr/bin/env node
/* Dependency-free WCAG contrast audit for the v10 token sheet.
   Usage: node scripts/check-contrast.js [--json] */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const TOKENS = path.join(ROOT, 'css', 'v10', 'tokens.css');
const REPORT = path.join(ROOT, 'docs', 'v10', 'contrast-report.md');

function declarations(block) {
  const out = {};
  const re = /(--[a-z0-9-]+)\s*:\s*([^;]+);/gi;
  let m;
  while ((m = re.exec(block))) out[m[1]] = m[2].trim();
  return out;
}

function blocks(css) {
  const scopes = [{ name: 'root', decls: declarations((css.match(/:root\s*\{([\s\S]*?)\}/) || [])[1] || '') }];
  const zoneRe = /\[data-zone="([a-z]+)"\]\s*\{([\s\S]*?)\}/g;
  let m;
  while ((m = zoneRe.exec(css))) scopes.push({ name: 'zone:' + m[1], decls: declarations(m[2]) });
  const slate = css.match(/\[data-slate="night"\]\s*\{([\s\S]*?)\}/);
  if (slate) scopes.push({ name: 'slate:night', decls: declarations(slate[1]) });
  return scopes;
}

function scopeFor(scopes, name) {
  return scopes.filter(s => s.name === name)[0] || { decls: {} };
}

function resolve(name, scopes, scope, seen) {
  seen = seen || {};
  if (seen[name]) throw new Error('cyclic token ' + name);
  seen[name] = true;
  const own = scopeFor(scopes, scope).decls[name];
  const root = scopeFor(scopes, 'root').decls[name];
  const raw = own != null ? own : root;
  if (raw == null) throw new Error('missing token ' + name + ' in ' + scope);
  const varMatch = raw.match(/^var\((--[a-z0-9-]+)\)$/i);
  if (varMatch) return resolve(varMatch[1], scopes, scope, seen);
  return raw;
}

function hexToRgb(value) {
  const s = String(value).trim();
  let m = s.match(/^#([0-9a-f]{3})$/i);
  if (m) return m[1].split('').map(c => parseInt(c + c, 16));
  m = s.match(/^#([0-9a-f]{6})$/i);
  if (m) return [0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16));
  throw new Error('not a hex colour: ' + value);
}

function luminance(rgb) {
  const c = rgb.map(v => {
    const s = v / 255;
    return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}

function ratio(fg, bg) {
  const a = luminance(hexToRgb(fg));
  const b = luminance(hexToRgb(bg));
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

const css = fs.readFileSync(TOKENS, 'utf8');
const scopes = blocks(css);
const rows = [];

function add(label, fgName, bgName, scope, required) {
  const fg = resolve(fgName, scopes, scope);
  const bg = resolve(bgName, scopes, scope);
  const value = ratio(fg, bg);
  rows.push({ label, scope, fg: fgName, bg: bgName, fgHex: fg, bgHex: bg, ratio: value, required, pass: value + 0.005 >= required });
}

const zones = ['shallows', 'twilight', 'midnight', 'abyss'];
for (const zone of zones) {
  const scope = 'zone:' + zone;
  for (const fg of ['--c-text', '--c-text-2', '--c-lantern-text', '--c-coral-text', '--c-kelp-text']) {
    add(zone + ' text', fg, '--c-bg', scope, 4.5);
    add(zone + ' raised text', fg, '--c-bg-raised', scope, 4.5);
  }
  add(zone + ' border on bg', '--c-line', '--c-bg', scope, 3);
  add(zone + ' border on raised', '--c-line', '--c-bg-raised', scope, 3);
}

for (const fg of ['--c-paper-text', '--c-paper-text-2', '--c-coral-ink', '--c-kelp-ink']) {
  add('paper text', fg, '--c-paper-bg', 'root', 4.5);
  add('paper-2 text', fg, '--c-paper-2', 'root', 4.5);
}
add('paper border', '--c-paper-line', '--c-paper-bg', 'root', 3);

for (const fg of ['--c-paper', '--c-mist', '--c-lantern-text', '--c-coral-text', '--c-kelp-text']) {
  add('night slate text', fg, '--c-slate-night', 'slate:night', 4.5);
}
add('night slate border', '--c-paper-line', '--c-slate-night', 'slate:night', 3);
add('primary button text', '--c-lantern-ink', '--c-lantern', 'root', 4.5);
add('coral fill text', '--c-lantern-ink', '--c-coral', 'root', 4.5);
add('kelp fill text', '--c-lantern-ink', '--c-kelp', 'root', 4.5);

const failed = rows.filter(r => !r.pass);
const lines = [];
lines.push('# Contrast report');
lines.push('');
lines.push('Generated by `scripts/check-contrast.js` from `css/v10/tokens.css`.');
lines.push('');
lines.push('WCAG 2.1 thresholds: normal text 4.5:1, non-text/UI boundaries 3:1. Large display type may use 3:1, but this report holds every token pair to the stricter text threshold.');
lines.push('');
lines.push('| Pair | Scope | Foreground | Background | Ratio | Required | Result |');
lines.push('| --- | --- | --- | --- | ---: | ---: | --- |');
for (const r of rows) {
  lines.push('| ' + r.label + ' | ' + r.scope + ' | `' + r.fgHex + '` | `' + r.bgHex + '` | ' + r.ratio.toFixed(2) + ':1 | ' + r.required.toFixed(1) + ':1 | ' + (r.pass ? 'Pass' : '**Fail**') + ' |');
}
lines.push('');
lines.push('**' + (rows.length - failed.length) + ' of ' + rows.length + ' pairs pass.**');
if (failed.length) {
  lines.push('');
  lines.push('Failures:');
  for (const r of failed) lines.push('- ' + r.label + ' (' + r.scope + '): ' + r.ratio.toFixed(2) + ':1, needs ' + r.required.toFixed(1) + ':1');
}
fs.mkdirSync(path.dirname(REPORT), { recursive: true });
fs.writeFileSync(REPORT, lines.join('\n') + '\n');

if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ total: rows.length, failed: failed.length, rows }, null, 2));
} else {
  console.log('contrast: ' + (rows.length - failed.length) + '/' + rows.length + ' pairs pass' + (failed.length ? ' — ' + failed.length + ' FAIL' : ''));
  for (const r of failed) console.log('  fail ' + r.label + ' ' + r.ratio.toFixed(2) + ':1 (need ' + r.required + ':1)');
}
process.exit(failed.length ? 1 : 0);
